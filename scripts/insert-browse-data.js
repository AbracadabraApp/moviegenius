#!/usr/bin/env node

/**
 * Insert Browse Collections into Railway Database
 *
 * Inserts transformed browse data (collections and movie assignments) into Railway PostgreSQL
 * Maps TMDB IDs to movie UUIDs and handles batch insertion efficiently
 */

import { transformBrowseData } from './transform-browse-data.js';
import { getRailwayClient } from '../lib/railway-db.js';

async function insertBrowseData() {
  console.log('🚀 Starting Browse Data Insertion...\n');

  const client = getRailwayClient();

  try {
    // Step 1: Transform browse data
    console.log('📊 Transforming browse data...');
    const { collections, movieAssignments, stats } = await transformBrowseData();
    console.log(`✅ Transformed ${collections.length} collections with ${movieAssignments.length} movie assignments\n`);

    // Step 2: Connect to database
    console.log('🔗 Connecting to Railway PostgreSQL...');
    await client.connect();
    console.log('✅ Connected\n');

    // Step 3: Check if schema exists
    console.log('🔍 Checking database schema...');
    const schemaCheck = await client.query(`
      SELECT table_name
      FROM information_schema.tables
      WHERE table_schema = 'public'
        AND table_name IN ('browse_lists', 'list_movies', 'movies')
      ORDER BY table_name
    `);

    const existingTables = schemaCheck.rows.map(r => r.table_name);
    console.log(`✅ Found tables: ${existingTables.join(', ')}\n`);

    if (!existingTables.includes('browse_lists') || !existingTables.includes('list_movies')) {
      throw new Error('Browse lists schema not installed! Run: node scripts/install-browse-schema.js');
    }

    if (!existingTables.includes('movies')) {
      throw new Error('Movies table not found! Browse collections require movies to exist.');
    }

    // Step 4: Verify movie UUIDs exist (JSON already contains UUIDs, not TMDB IDs)
    console.log('🔍 Verifying movie UUIDs...');
    const movieCheck = await client.query(`
      SELECT COUNT(*) FROM movies
    `);
    console.log(`✅ ${movieCheck.rows[0].count} movies in database\n`);

    // Step 5: Insert collections (in batches for efficiency)
    // Map old string IDs to new UUIDs generated by database
    console.log('📝 Inserting browse collections...');
    await client.query('BEGIN');

    let collectionsInserted = 0;
    let collectionsSkipped = 0;
    const COLLECTION_BATCH_SIZE = 50;

    // Map old collection IDs to new UUIDs
    const oldIdToNewUuid = new Map();

    for (let i = 0; i < collections.length; i += COLLECTION_BATCH_SIZE) {
      const batch = collections.slice(i, i + COLLECTION_BATCH_SIZE);

      for (const collection of batch) {
        try {
          // Let PostgreSQL generate UUID, return it so we can map movie assignments
          const result = await client.query(`
            INSERT INTO browse_lists (
              title, description, total_movies, status, created_at, updated_at
            ) VALUES ($1, $2, $3, $4, $5, $6)
            ON CONFLICT (title) DO UPDATE
              SET updated_at = EXCLUDED.updated_at
            RETURNING id
          `, [
            collection.title,
            collection.description,
            collection.total_movies,
            collection.status,
            collection.created_at,
            collection.updated_at
          ]);

          // Map old ID to new UUID
          const newUuid = result.rows[0].id;
          oldIdToNewUuid.set(collection.id, newUuid);

          collectionsInserted++;
        } catch (error) {
          console.error(`  ⚠️  Skipped collection "${collection.title}": ${error.message}`);
          collectionsSkipped++;
        }
      }

      // Progress indicator
      const progress = Math.min(i + COLLECTION_BATCH_SIZE, collections.length);
      process.stdout.write(`  Progress: ${progress}/${collections.length} collections...\r`);
    }

    console.log(`\n✅ Inserted ${collectionsInserted} collections (${collectionsSkipped} skipped)\n`);

    // Step 6: Insert movie assignments (with UUID mapping) - BATCH MODE
    console.log('🎬 Inserting movie assignments (batch mode)...');

    let assignmentsInserted = 0;
    let assignmentsMissingMovie = 0;
    let assignmentsSkipped = 0;
    const BATCH_SIZE = 1000;

    // Prepare all valid assignments (movie_id is already a UUID from transform)
    const validAssignments = [];

    for (const assignment of movieAssignments) {
      const listUuid = oldIdToNewUuid.get(assignment.list_id);
      const movieUuid = assignment.movie_id; // Already a UUID!

      if (!listUuid) {
        assignmentsSkipped++;
        continue;
      }

      if (!movieUuid) {
        assignmentsMissingMovie++;
        continue;
      }

      validAssignments.push({
        listUuid,
        movieUuid,
        relevance_score: assignment.relevance_score,
        display_order: assignment.display_order
      });
    }

    console.log(`  Prepared ${validAssignments.length} valid assignments for batch insert`);

    // Batch insert valid assignments
    for (let i = 0; i < validAssignments.length; i += BATCH_SIZE) {
      const batch = validAssignments.slice(i, i + BATCH_SIZE);

      // Build multi-value INSERT
      const values = [];
      const params = [];
      let paramIndex = 1;

      batch.forEach(assignment => {
        values.push(`($${paramIndex}, $${paramIndex+1}, $${paramIndex+2}, $${paramIndex+3}, NOW())`);
        params.push(
          assignment.listUuid,
          assignment.movieUuid,
          assignment.relevance_score,
          assignment.display_order
        );
        paramIndex += 4;
      });

      try {
        await client.query(`
          INSERT INTO list_movies (
            list_id, movie_id, relevance_score, display_order, added_at
          ) VALUES ${values.join(', ')}
          ON CONFLICT (list_id, movie_id) DO NOTHING
        `, params);

        assignmentsInserted += batch.length;
        process.stdout.write(`  Progress: ${Math.min(i + BATCH_SIZE, validAssignments.length)}/${validAssignments.length} assignments...\r`);
      } catch (error) {
        console.error(`\n  ⚠️  Batch insert failed: ${error.message}`);
        assignmentsSkipped += batch.length;
      }
    }

    console.log(`\n✅ Inserted ${assignmentsInserted} movie assignments`);
    console.log(`   ${assignmentsMissingMovie} movies not found in database`);
    console.log(`   ${assignmentsSkipped} assignments skipped\n`);

    await client.query('COMMIT');

    // Step 7: Verify insertion
    console.log('🔍 Verifying insertion...');
    const verifyQuery = await client.query(`
      SELECT
        (SELECT COUNT(*) FROM browse_lists WHERE status = 'active') as active_lists,
        (SELECT COUNT(*) FROM list_movies) as total_assignments,
        (SELECT AVG(total_movies) FROM browse_lists) as avg_movies_per_list
    `);

    const verification = verifyQuery.rows[0];
    console.log(`✅ Verification:`);
    console.log(`   Active lists: ${verification.active_lists}`);
    console.log(`   Total assignments: ${verification.total_assignments}`);
    console.log(`   Average movies per list: ${parseFloat(verification.avg_movies_per_list).toFixed(1)}`);

    await client.end();

    console.log('\n🎉 Browse data insertion complete!');
    console.log('\n📝 Next steps:');
    console.log('   1. Test search: node scripts/test-browse-search.js');
    console.log('   2. Update /api/universal-search to query database');
    console.log('   3. Verify data quality: node scripts/check-browse-schema.js');

  } catch (error) {
    console.error('\n❌ Insertion failed:', error);

    try {
      await client.query('ROLLBACK');
      console.log('🔄 Transaction rolled back');
    } catch (rollbackError) {
      console.error('Failed to rollback:', rollbackError.message);
    }

    try {
      await client.end();
    } catch (endError) {
      // Ignore
    }

    process.exit(1);
  }
}

// Run if executed directly
if (import.meta.url === `file://${process.argv[1]}`) {
  insertBrowseData();
}

export { insertBrowseData };
