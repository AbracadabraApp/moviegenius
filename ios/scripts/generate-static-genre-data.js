#!/usr/bin/env node
/**
 * Generate static Swift file with all genre tier film data
 * Eliminates network calls and race conditions
 */

const { Pool } = require('pg');
const fs = require('fs');

// All genre tier films from GeniusView.swift
const genreTiers = {
  "Mystery": {
    "Connoisseur": [
      ["Charade", 1963],
      ["Wait Until Dark", 1967],
      ["The Manchurian Candidate", 1962],
      ["Klute", 1971],
      ["The Parallax View", 1974],
      ["Three Days of the Condor", 1975],
      ["Marathon Man", 1976],
      ["All the President's Men", 1976],
      ["The Onion Field", 1979],
      ["Cutter's Way", 1981],
      ["Body Double", 1984],
      ["Blow Out", 1981],
      ["House of Games", 1987],
      ["The Vanishing", 1993],
      ["Jagged Edge", 1985],
      ["No Way Out", 1987],
      ["The Morning After", 1986],
      ["Frantic", 1988],
      ["Presumed Innocent", 1990],
      ["Final Analysis", 1992]
    ]
  }
};

async function main() {
  const pool = new Pool({ connectionString: process.env.DATABASE_URL });

  const output = [];
  output.push('//');
  output.push('//  GenreTierStaticData.swift');
  output.push('//  moviegenius');
  output.push('//');
  output.push('//  Static genre tier film data - eliminates network calls');
  output.push('//  Generated by generate-static-genre-data.js');
  output.push('//');
  output.push('');
  output.push('import Foundation');
  output.push('');
  output.push('struct StaticGenreFilm {');
  output.push('    let title: String');
  output.push('    let year: Int');
  output.push('    let tmdbId: Int');
  output.push('    let slug: String');
  output.push('    let posterUrl: String?');
  output.push('}');
  output.push('');
  output.push('struct GenreTierStaticData {');

  for (const [genre, tiers] of Object.entries(genreTiers)) {
    for (const [tier, films] of Object.entries(tiers)) {
      output.push(`    // ${genre} > ${tier} (${films.length} films)`);
      output.push(`    static let ${genre.toLowerCase()}_${tier.toLowerCase()}: [StaticGenreFilm] = [`);

      for (const [title, year] of films) {
        // Query database
        const result = await pool.query(
          'SELECT tmdb_id, title, year, slug, poster_url FROM movies WHERE title = $1 AND year = $2',
          [title, year]
        );

        if (result.rows.length === 0) {
          console.error(`⚠️  Not found: ${title} (${year})`);
          continue;
        }

        const movie = result.rows[0];
        const escapedTitle = movie.title.replace(/"/g, '\\"');
        const escapedSlug = (movie.slug || '').replace(/"/g, '\\"');
        const posterUrl = movie.poster_url || 'nil';
        const posterUrlStr = posterUrl === 'nil' ? 'nil' : `"${posterUrl}"`;

        output.push(`        StaticGenreFilm(`);
        output.push(`            title: "${escapedTitle}",`);
        output.push(`            year: ${movie.year},`);
        output.push(`            tmdbId: ${movie.tmdb_id},`);
        output.push(`            slug: "${escapedSlug}",`);
        output.push(`            posterUrl: ${posterUrlStr}`);
        output.push(`        ),`);
      }

      output.push(`    ]`);
      output.push('');
    }
  }

  output.push('}');

  // Write to file
  const swiftFile = '/Users/josh.petersen/moviegenius/ios/moviegenius/moviegenius/GenreTierStaticData.swift';
  fs.writeFileSync(swiftFile, output.join('\n'));

  console.log(`✅ Generated ${swiftFile}`);
  console.log(`📊 Total films: ${genreTiers.Mystery.Connoisseur.length}`);

  await pool.end();
}

main().catch(console.error);
